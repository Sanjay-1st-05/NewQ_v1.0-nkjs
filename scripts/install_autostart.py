"""NewQ Stage 8b — install/uninstall the tray server as a Windows Startup item.

Writes a small VBS launcher into the user's Startup folder (shell:startup)
so Windows runs scripts/server_tray.py via pythonw.exe — headless, no
console window — every time the user logs in.

Usage:
    .venv\\Scripts\\python.exe scripts\\install_autostart.py           # install
    .venv\\Scripts\\python.exe scripts\\install_autostart.py --remove  # uninstall
    .venv\\Scripts\\python.exe scripts\\install_autostart.py --status  # check only

Idempotent: installing again just rewrites the launcher with current paths.
"""

import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LAUNCHER_NAME = 'NewQ Server (tray).vbs'

VBS_TEMPLATE = (
    "' NewQ backend auto-start (generated by scripts/install_autostart.py).\n"
    "' Runs the tray controller headlessly: pythonw has no console window.\n"
    'CreateObject("WScript.Shell").Run """{pythonw}"" ""{tray}""", 0\n'
)


def startup_dir():
    # %APPDATA%\Microsoft\Windows\Start Menu\Programs\Startup (shell:startup)
    appdata = os.environ.get('APPDATA')
    return Path(appdata) / 'Microsoft' / 'Windows' / 'Start Menu' / 'Programs' / 'Startup'


def launcher_path():
    return startup_dir() / LAUNCHER_NAME


def render_vbs():
    pythonw = REPO_ROOT / '.venv' / 'Scripts' / 'pythonw.exe'
    tray = REPO_ROOT / 'scripts' / 'server_tray.py'
    if not pythonw.is_file():
        raise SystemExit(f'pythonw not found at {pythonw}')
    if not tray.is_file():
        raise SystemExit(f'tray script not found at {tray}')
    return VBS_TEMPLATE.format(pythonw=pythonw, tray=tray)


def install():
    launcher = launcher_path()
    launcher.parent.mkdir(parents=True, exist_ok=True)
    launcher.write_text(render_vbs(), encoding='utf-16')
    print(f'installed: {launcher}')
    print('the NewQ server will start in the tray at next logon')


def remove():
    launcher = launcher_path()
    if launcher.is_file():
        launcher.unlink()
        print(f'removed: {launcher}')
    else:
        print('not installed — nothing to remove')


def status():
    launcher = launcher_path()
    if launcher.is_file():
        print(f'installed: {launcher}')
    else:
        print('not installed')


def main(argv):
    flag = argv[1] if len(argv) > 1 else ''
    if flag == '--remove':
        remove()
    elif flag == '--status':
        status()
    else:
        install()
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
